"""Where uploaded archives, repository mirrors and test logs live: S3 (SSE-KMS) in every
real deployment, local disk otherwise.

Keys are generated by CodeAgent (see the `*_key` helpers below), never taken from user
input, and the local backend still refuses any key that could escape its root directory.
Mirrors can be large, so they move between storage and the worker's disk as files
(`put_file`, `get_file`) and never pass through memory whole.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
from collections.abc import AsyncIterator
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

import anyio
from botocore.exceptions import ClientError

from codeagent.core.config import Settings
from codeagent.core.errors import NotFoundError, ServiceUnavailableError
from codeagent.integrations import aws

if TYPE_CHECKING:
    from botocore.response import StreamingBody
    from mypy_boto3_s3.type_defs import ObjectIdentifierTypeDef

_SAFE_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/_.-]{0,399}$")
CHUNK_SIZE = 1024 * 1024


class Storage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def put_file(self, key: str, path: Path, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def get_file(self, key: str, path: Path) -> None: ...

    def stream(self, key: str) -> AsyncIterator[bytes]: ...

    async def delete(self, key: str) -> None: ...

    async def delete_prefix(self, prefix: str) -> int: ...

    async def check(self) -> None: ...


def repository_prefix(workspace_id: object, repository_id: object) -> str:
    return f"workspaces/{workspace_id}/repositories/{repository_id}/"


def upload_key(
    workspace_id: object, repository_id: object, snapshot_id: object, suffix: str
) -> str:
    """An uploaded archive, kept so a snapshot can be rebuilt from exactly what was sent."""
    return f"{repository_prefix(workspace_id, repository_id)}uploads/{snapshot_id}{suffix}"


def mirror_key(workspace_id: object, repository_id: object) -> str:
    """The working tree with its .git directory, as a gzip tarball."""
    return f"{repository_prefix(workspace_id, repository_id)}mirror.tar.gz"


def test_log_key(workspace_id: object, test_run_id: object) -> str:
    return f"workspaces/{workspace_id}/test-runs/{test_run_id}/log.txt"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _SAFE_KEY.match(key) or ".." in key.split("/"):
            raise ValueError(f"unsafe storage key: {key!r}")
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"storage key escapes the root: {key!r}")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Write then rename, so a reader never sees a half-written file.
            fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.replace(tmp, path)

        await anyio.to_thread.run_sync(write)

    async def put_file(self, key: str, path: Path, content_type: str) -> None:
        target = self._path(key)

        def copy() -> None:
            target.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=".upload-")
            os.close(fd)
            shutil.copyfile(path, tmp)
            os.replace(tmp, target)

        await anyio.to_thread.run_sync(copy)

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await anyio.Path(path).read_bytes()
        except FileNotFoundError as exc:
            raise NotFoundError("The stored object is missing.") from exc

    async def get_file(self, key: str, path: Path) -> None:
        source = self._path(key)
        if not source.exists():
            raise NotFoundError("The stored object is missing.")
        await anyio.to_thread.run_sync(shutil.copyfile, source, path)

    async def stream(self, key: str) -> AsyncIterator[bytes]:
        path = self._path(key)
        try:
            async with await anyio.open_file(path, "rb") as handle:
                while chunk := await handle.read(CHUNK_SIZE):
                    yield chunk
        except FileNotFoundError as exc:
            raise NotFoundError("The stored object is missing.") from exc

    async def delete(self, key: str) -> None:
        await anyio.to_thread.run_sync(lambda: self._path(key).unlink(missing_ok=True))

    async def delete_prefix(self, prefix: str) -> int:
        directory = self._path(prefix.rstrip("/"))

        def remove() -> int:
            if not directory.is_dir():
                return 0
            count = sum(1 for p in directory.rglob("*") if p.is_file())
            shutil.rmtree(directory, ignore_errors=True)
            return count

        return await anyio.to_thread.run_sync(remove)

    async def check(self) -> None:
        await anyio.to_thread.run_sync(lambda: self.root.mkdir(parents=True, exist_ok=True))


class S3Storage:
    def __init__(self, settings: Settings) -> None:
        if not settings.s3_bucket:
            raise ValueError("S3_BUCKET is required for STORAGE_BACKEND=s3")
        self.bucket = settings.s3_bucket
        self.kms_key_id = settings.s3_kms_key_id
        self._client = aws.s3_client(settings)

    def _encryption(self) -> dict[str, Any]:
        if self.kms_key_id:
            return {"ServerSideEncryption": "aws:kms", "SSEKMSKeyId": self.kms_key_id}
        return {}

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        extra = self._encryption()
        await anyio.to_thread.run_sync(
            lambda: self._client.put_object(
                Bucket=self.bucket, Key=key, Body=data, ContentType=content_type, **extra
            )
        )

    async def put_file(self, key: str, path: Path, content_type: str) -> None:
        # The managed transfer streams from disk and switches to multipart for large files.
        extra_args = {"ContentType": content_type, **self._encryption()}
        await anyio.to_thread.run_sync(
            lambda: self._client.upload_file(str(path), self.bucket, key, ExtraArgs=extra_args)
        )

    async def _body(self, key: str) -> StreamingBody:
        try:
            response = await anyio.to_thread.run_sync(
                lambda: self._client.get_object(Bucket=self.bucket, Key=key)
            )
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in {"NoSuchKey", "404"}:
                raise NotFoundError("The stored object is missing.") from exc
            raise
        return response["Body"]

    async def get(self, key: str) -> bytes:
        body = await self._body(key)
        try:
            data: bytes = await anyio.to_thread.run_sync(body.read)
        finally:
            body.close()
        return data

    async def get_file(self, key: str, path: Path) -> None:
        try:
            await anyio.to_thread.run_sync(
                lambda: self._client.download_file(self.bucket, key, str(path))
            )
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in {"NoSuchKey", "404"}:
                raise NotFoundError("The stored object is missing.") from exc
            raise

    async def stream(self, key: str) -> AsyncIterator[bytes]:
        """Chunk by chunk, so a download never holds the whole file in memory."""
        body = await self._body(key)
        try:
            while chunk := await anyio.to_thread.run_sync(body.read, CHUNK_SIZE):
                yield chunk
        finally:
            body.close()

    async def delete(self, key: str) -> None:
        await anyio.to_thread.run_sync(
            lambda: self._client.delete_object(Bucket=self.bucket, Key=key)
        )

    async def delete_prefix(self, prefix: str) -> int:
        """Delete every object under a prefix (a versioned bucket keeps the old versions)."""

        def remove() -> int:
            deleted = 0
            paginator = self._client.get_paginator("list_objects_v2")
            for page in paginator.paginate(Bucket=self.bucket, Prefix=prefix):
                keys: list[ObjectIdentifierTypeDef] = [
                    {"Key": item["Key"]} for item in page.get("Contents", [])
                ]
                if keys:
                    self._client.delete_objects(
                        Bucket=self.bucket, Delete={"Objects": keys, "Quiet": True}
                    )
                    deleted += len(keys)
            return deleted

        return await anyio.to_thread.run_sync(remove)

    async def check(self) -> None:
        try:
            await anyio.to_thread.run_sync(lambda: self._client.head_bucket(Bucket=self.bucket))
        except ClientError as exc:
            raise ServiceUnavailableError("The repository bucket is not reachable.") from exc


def build_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(settings.storage_dir)
